"""Explicit query and transaction boundary; no transport or ORM dependencies."""

from collections.abc import Sequence
from datetime import datetime
from typing import Protocol
from uuid import UUID

from ted.domain.models import (
    Audit,
    Client,
    Delivery,
    Invoice,
    InvoiceLine,
    LoginSession,
    Payment,
    Project,
    Task,
    TimeEntry,
    User,
    Webhook,
    Workspace,
)


class Store(Protocol):
    async def workspace(self, lock: bool = False) -> Workspace: ...
    async def user(self, id: UUID, lock: bool = False) -> User: ...
    async def user_by_email(self, email: str) -> User | None: ...
    async def users(self) -> Sequence[User]: ...
    async def session(self, token_hash: str) -> LoginSession | None: ...
    async def delete_sessions(self, user_id: UUID) -> None: ...
    async def client(self, id: UUID) -> Client: ...
    async def clients(self, actor: User) -> Sequence[Client]: ...
    async def project(self, id: UUID) -> Project: ...
    async def projects(self, actor: User) -> Sequence[Project]: ...
    async def members(self, project_id: UUID) -> list[UUID]: ...
    async def set_members(self, project_id: UUID, ids: list[UUID]) -> None: ...
    async def task(self, id: UUID, lock: bool = False) -> Task: ...
    async def tasks(self, actor: User) -> Sequence[Task]: ...
    async def assignees(self, task_id: UUID) -> list[UUID]: ...
    async def set_assignees(self, task_id: UUID, ids: list[UUID]) -> None: ...
    async def entry(self, id: UUID, lock: bool = False) -> TimeEntry | None: ...
    async def entries(self, actor: User) -> Sequence[TimeEntry]: ...
    async def active_entry(self, user_id: UUID) -> TimeEntry | None: ...
    async def overlaps(
        self, user_id: UUID, start: datetime, end: datetime, exclude: UUID
    ) -> bool: ...
    async def invoice(self, id: UUID) -> Invoice: ...
    async def invoice_by_key(self, key: UUID) -> Invoice | None: ...
    async def invoices(self) -> Sequence[Invoice]: ...
    async def lines(self, invoice_id: UUID | None = None) -> Sequence[InvoiceLine]: ...
    async def payments(self, invoice_id: UUID | None = None) -> Sequence[Payment]: ...
    async def payment_by_key(self, key: UUID) -> Payment | None: ...
    async def audits(self) -> Sequence[Audit]: ...
    async def webhooks(self) -> Sequence[Webhook]: ...
    async def deliveries(self) -> Sequence[Delivery]: ...
    async def save(self, *entities: object) -> None: ...


class Passwords(Protocol):
    dummy_hash: str

    def hash(self, password: str) -> str: ...
    def verify(self, password: str, hashed: str) -> bool: ...
